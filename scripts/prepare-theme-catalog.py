#!/usr/bin/env python3
"""Embed attributed Ghostty files without adding a runtime filesystem dependency."""
from pathlib import Path
import json
import sys
ROOT = Path(__file__).resolve().parent.parent
ENTRIES = [("Dracula", "dracula/dracula"), ("Catppuccin Mocha", "catppuccin/catppuccin-mocha.conf"),
           ("Catppuccin Macchiato", "catppuccin/catppuccin-macchiato.conf"),
           ("Catppuccin Frappe", "catppuccin/catppuccin-frappe.conf"),
           ("Catppuccin Latte", "catppuccin/catppuccin-latte.conf")]
text = "/* Generated by scripts/prepare-theme-catalog.py; see themes/README.md and licenses. */\n"
text += "static const char *const theme_bundled_names[] = {\n" + "".join("    " + json.dumps(name) + ",\n" for name, _ in ENTRIES) + "};\n"
text += "static const char *const theme_bundled_sources[] = {\n" + "".join("    " + json.dumps((ROOT / "themes" / path).read_text()) + ",\n" for _, path in ENTRIES) + "};\n"
output = ROOT / "spikes/ghostling/theme_catalog_data.h"
if "--check" in sys.argv:
    if not output.exists() or output.read_text() != text:
        sys.exit("Theme catalog header is stale; run python3 scripts/prepare-theme-catalog.py")
else:
    if not output.exists() or output.read_text() != text:
        output.write_text(text)
